import { expect, test, type Page } from '@playwright/test';

import { stubRemotePhotos } from './stubPhotos';

// Full-page visual baselines for every page, once per Playwright project (desktop Chrome, Pixel 7, iPhone 15).
//
// Baselines are rendered by .github/workflows/update-snapshots.yml in the Playwright container image on Linux, the same
// image CI's e2e job uses, and committed by that workflow. Playwright puts the platform in each snapshot's file name
// (`home-chromium-desktop-linux.png`), so a baseline made on Windows or macOS would never match CI's run. Those runs
// are therefore skipped unless VISUAL_LOCAL=1, which is for proving the spec works, and their files are git-ignored.
test.skip(
    process.platform !== 'linux' && !process.env.VISUAL_LOCAL,
    'Visual baselines are Linux-only; regenerate them with the "Update visual snapshots" workflow (VISUAL_LOCAL=1 forces a local run).',
);

// WebKit cannot capture a screenshot over 32,767 device pixels on either side, and the iPhone project renders at 3x, so
// a long page (the Photography page with a full gallery) is captured only down to this many CSS pixels.
const MAX_CAPTURE_HEIGHT = 8000;

const PAGES = [
    { name: 'home', path: '/' },
    { name: 'photography', path: '/photography/' },
    { name: 'art', path: '/art/' },
    { name: 'projects', path: '/projects/' },
] as const;

// The project cards show GitHub's About text and topics, which a daily bot PR refreshes and auto-merges only when the
// checks pass. A longer description or one more chip wraps differently and moves everything below it, which masking
// cannot hide, so this spec would fail on a data-only change. Before the screenshot the page's copy is therefore
// replaced with fixed stand-ins, so the baseline depends on the layout and never on the live text.
const PLACEHOLDER_DESCRIPTION =
    'A placeholder description of fixed length that stands in for the text on GitHub, long enough to wrap onto a second line in a narrow column.';
const PLACEHOLDER_CHIPS = ['Chip one', 'Chip two', 'Chip three', 'Chip four'];
const PLACEHOLDER_DATE = 'Jan 1, 2026';

// The screenshots are regenerated by the sync and differ in bytes, not in size, so they are stubbed with one flat image
// of the same 16:10 shape (the img's width and height reserve the space either way).
const PLACEHOLDER_SCREENSHOT = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1600 1000"><rect width="1600" height="1000" fill="#808080"/></svg>`;

async function stubProjectScreenshots(page: Page): Promise<void> {
    await page.route(/\/_astro\/[^/]+\.(avif|webp)(\?.*)?$/, (route) =>
        route.fulfill({ status: 200, contentType: 'image/svg+xml', body: PLACEHOLDER_SCREENSHOT }),
    );
}

async function fixProjectCopy(page: Page): Promise<void> {
    await page.evaluate(
        ({ description, chips, date }) => {
            for (const element of document.querySelectorAll('[data-project-description]'))
                element.textContent = description;
            for (const list of document.querySelectorAll('[data-project-tech]')) {
                const template = list.querySelector('li');
                if (!template) continue;
                // Clones of the first chip, so the classes (and so the styling) are exactly the page's own.
                list.replaceChildren(
                    ...chips.map((text) => {
                        const chip = template.cloneNode(true) as HTMLElement;
                        chip.textContent = text;
                        return chip;
                    }),
                );
            }
            for (const time of document.querySelectorAll('article time')) time.textContent = date;
        },
        { description: PLACEHOLDER_DESCRIPTION, chips: PLACEHOLDER_CHIPS, date: PLACEHOLDER_DATE },
    );
}

async function waitForStablePage(page: Page): Promise<void> {
    // The fonts are swapped in after first paint; a screenshot before then would catch the fallback faces.
    await page.evaluate(() => document.fonts.ready);
    // The gallery tiles use content-visibility:auto, so a full-page screenshot, which does not scroll, would leave
    // every tile below the fold unrendered. Force them to render so the baseline shows the whole page.
    await page.addStyleTag({ content: '* { content-visibility: visible !important; }' });
    // A full-page screenshot does not scroll, so lazy images below the fold would never load without this.
    await page.evaluate(async () => {
        const images = [...document.images];
        for (const image of images) image.loading = 'eager';
        await Promise.all(images.map((image) => image.decode().catch(() => undefined)));
    });
}

test.describe('visual baseline', () => {
    test.use({ reducedMotion: 'reduce' });

    for (const { name, path } of PAGES) {
        test(`${path} matches its baseline`, async ({ page }) => {
            await stubRemotePhotos(page);
            if (name === 'projects') await stubProjectScreenshots(page);
            await page.goto(path);
            if (name === 'projects') await fixProjectCopy(page);
            await waitForStablePage(page);

            const { width, height } = await page.evaluate(() => ({
                width: document.documentElement.clientWidth,
                height: document.documentElement.scrollHeight,
            }));

            await expect(page).toHaveScreenshot(`${name}.png`, {
                fullPage: true,
                clip: { x: 0, y: 0, width, height: Math.min(height, MAX_CAPTURE_HEIGHT) },
                animations: 'disabled',
                // The footer carries the build year and the project cards a last-commit date; both change with time
                // alone, so they are masked rather than baked into a baseline that would break on its own.
                mask: [page.locator('footer'), page.locator('time')],
                maxDiffPixelRatio: 0.001,
            });
        });
    }
});
